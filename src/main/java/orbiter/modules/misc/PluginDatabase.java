    private static void ch(String pattern) {
        String p = pattern.toLowerCase().trim();
        if (p.isEmpty()) return;
        String ns = p.contains(":") ? p.substring(0, p.indexOf(":")) : p;
        String name = NAMESPACE_ALIASES.getOrDefault(ns, humanize(ns));
        PluginEntry entry = new PluginEntry(name, "Unknown");
        if (p.endsWith(":*")) {
            WILDCARD_DB.put(p, entry);
        } else {
            EXACT_DB.put(p, entry);
        }
    }

    private static String humanize(String ns) {
        if (ns == null || ns.isEmpty()) return ns;
        StringBuilder sb = new StringBuilder();
        for (String part : ns.split("[_\\-]")) {
            if (part.isEmpty()) continue;
            sb.append(Character.toUpperCase(part.charAt(0)));
            if (part.length() > 1) sb.append(part.substring(1));
            sb.append(' ');
        }
        return sb.toString().trim();
    }

    public static PluginEntry lookupChannel(String channel) {
        if (channel == null) return null;
        String lower = channel.toLowerCase();

        PluginEntry entry = EXACT_DB.get(lower);
        if (entry != null) return entry;

        int colon = lower.indexOf(':');
        if (colon > 0) {
            String ns = lower.substring(0, colon);
            entry = WILDCARD_DB.get(ns + ":*");
            if (entry != null) return entry;
        }

        for (var e : WILDCARD_DB.entrySet()) {
            String pattern = e.getKey();
            if (pattern.endsWith(":*")) {
                String prefix = pattern.substring(0, pattern.length() - 2);
                if (lower.startsWith(prefix + ":") || lower.equals(prefix)) return e.getValue();
            }
        }

        return fuzzyLookup(lower);
    }

    public static PluginEntry lookupCommand(String command) {
        if (command == null) return null;
        String lower = command.toLowerCase().replace("/", "").trim();
        return COMMAND_DB.get(lower);
    }

    public static String resolveNamespace(String ns) {
        return ns == null ? null : NAMESPACE_ALIASES.get(ns.toLowerCase());
    }

    public static boolean isNonPluginNamespace(String ns) {
        return ns != null && NON_PLUGIN_NAMESPACES.contains(ns.toLowerCase());
    }

    public static List<String> extractChannelTokens(byte[] raw) {
        List<String> tokens = new ArrayList<>();
        if (raw == null || raw.length == 0) return tokens;
        try {
            String text = new String(raw, java.nio.charset.StandardCharsets.UTF_8);
            Matcher m = CHANNEL_TOKEN.matcher(text);
            while (m.find()) {
                String t = m.group().toLowerCase();
                if (!isNonPluginNamespace(t.split(":")[0])) tokens.add(t);
            }
        } catch (Exception ignored) {}
        return tokens;
    }

    public static List<String> extractRegisteredChannels(byte[] raw) {
        List<String> channels = new ArrayList<>();
        if (raw == null || raw.length == 0) return channels;
        try {
            String text = new String(raw, java.nio.charset.StandardCharsets.UTF_8);
            for (String part : text.split("\0")) {
                String t = part.trim().toLowerCase();
                if (!t.isEmpty()) channels.add(t);
            }
        } catch (Exception ignored) {}
        return channels;
    }

    public static int levenshtein(String s, String t) {
        if (s.isEmpty()) return t.length();
        if (t.isEmpty()) return s.length();
        int[] prev = new int[t.length() + 1];
        for (int j = 0; j <= t.length(); j++) prev[j] = j;
        for (int i = 1; i <= s.length(); i++) {
            int[] curr = new int[t.length() + 1];
            curr[0] = i;
            for (int j = 1; j <= t.length(); j++) {
                int cost = s.charAt(i - 1) == t.charAt(j - 1) ? 0 : 1;
                curr[j] = Math.min(Math.min(curr[j - 1] + 1, prev[j] + 1), prev[j - 1] + cost);
            }
            prev = curr;
        }
        return prev[t.length()];
    }

    private static PluginEntry fuzzyLookup(String input) {
        if (input.length() < 4) return null;
        PluginEntry best = null;
        int bestDist = Integer.MAX_VALUE;
        for (var e : WILDCARD_DB.entrySet()) {
            String key = e.getKey().replace(":*", "");
            int dist = levenshtein(input, key);
            if (dist < bestDist && dist <= 2) { bestDist = dist; best = e.getValue(); }
        }
        for (var e : EXACT_DB.entrySet()) {
            int dist = levenshtein(input, e.getKey());
            if (dist < bestDist && dist <= 2) { bestDist = dist; best = e.getValue(); }
        }
        return best;
    }

